"""Derive the bot's env file from the watcher's `.env` (#45).

    python -m story_watch.bot.envfile /opt/story-watch/.env > bot.env

Only the keys in BOT_ENV_KEYS are copied (an allowlist: a setting added to `.env` later stays out
of the bot until someone adds it there), so the bot's user never holds the Claude token, the
Instagram settings or anything else the watcher has. install.sh runs this as root on every deploy.
No value is ever printed to stderr or put in an error message.
"""

from __future__ import annotations

import re
import sys
from typing import Mapping

from dotenv import dotenv_values

from .config import BOT_ENV_KEYS

# Values written without quotes. Anything else is double-quoted, which systemd's EnvironmentFile=
# reads with C-style escapes (and python-dotenv the same way).
_PLAIN = re.compile(r"[A-Za-z0-9_./:,@+=%-]*")
_CONTROL = re.compile(r"[\x00-\x1f\x7f]")

HEADER = "# Generated by deploy/install.sh from .env (story_watch/bot/envfile.py). Don't edit: the next deploy overwrites it.\n"


class EnvFileError(ValueError):
    pass


def bot_env(values: Mapping[str, str | None]) -> dict[str, str]:
    """The allowlisted subset of `values`, in BOT_ENV_KEYS order. Keys without a value are left out."""
    return {key: values[key] for key in BOT_ENV_KEYS if values.get(key) is not None}  # type: ignore[misc]


def _quote(key: str, value: str) -> str:
    if _PLAIN.fullmatch(value):
        return value
    if _CONTROL.search(value):
        raise EnvFileError(f"{key}: the value has a line break or control character")
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(values: Mapping[str, str]) -> str:
    return HEADER + "".join(f"{key}={_quote(key, value)}\n" for key, value in values.items())


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 1:
        print("usage: python -m story_watch.bot.envfile <path to .env>", file=sys.stderr)
        return 2
    try:
        with open(argv[0], encoding="utf-8") as fh:
            text = render(bot_env(dotenv_values(stream=fh, interpolate=False)))
    except (OSError, EnvFileError) as e:
        # EnvFileError names the key only; an OSError names the path only.
        print(f"envfile: {e if isinstance(e, EnvFileError) else type(e).__name__}", file=sys.stderr)
        return 1
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
